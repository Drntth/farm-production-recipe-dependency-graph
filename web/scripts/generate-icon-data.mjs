// Generates src/components/icon-data.ts: the Lucide icons of the concept table in
// docs/ui-design.md, copied from @iconify-json/lucide, so Svelte islands ship only those.
// Run after changing the table or the package: node scripts/generate-icon-data.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";

const UI_DESIGN = fileURLToPath(new URL("../../docs/ui-design.md", import.meta.url));
const LUCIDE = fileURLToPath(new URL("../node_modules/@iconify-json/lucide/icons.json", import.meta.url));
const OUTPUT = fileURLToPath(new URL("../src/components/icon-data.ts", import.meta.url));

/** Lucide names of the "Concept icons and legend" table (second column, backticked). */
export function documentedIcons(markdown) {
  const section = markdown.slice(markdown.indexOf("## Concept icons and legend"), markdown.indexOf("## Item drawings"));
  return section
    .split("\n")
    .map((line) => line.match(/^\|[^|]+\|\s*`([a-z0-9-]+)`\s*\|/))
    .filter(Boolean)
    .map((m) => m[1]);
}

export function readLucideIcons() {
  return JSON.parse(readFileSync(LUCIDE, "utf8"));
}

/** Escapes a string for a template literal (kept as-is by prettier). */
function literal(s) {
  return "`" + s.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${") + "`";
}

/** Source of icon-data.ts for the given names; throws on an unknown name. */
export function buildIconData(lucide, names) {
  const entries = names.map((name) => {
    const icon = lucide.icons[name];
    if (!icon) throw new Error(`Lucide icon not found: ${name}`);
    const body = icon.body;
    const key = /^[A-Za-z_]\w*$/.test(name) ? name : `"${name}"`; // prettier unquotes plain keys
    return `  ${key}: {\n    body: ${literal(body)},\n  },`;
  });
  return [
    "// Generated by web/scripts/generate-icon-data.mjs from docs/ui-design.md and @iconify-json/lucide. Do not edit.",
    "",
    "export const LUCIDE_ICONS = {",
    ...entries,
    "} as const;",
    "",
    "export type IconName = keyof typeof LUCIDE_ICONS;",
    "",
  ].join("\n");
}

// Run as a script (not when imported by the tests).
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const names = documentedIcons(readFileSync(UI_DESIGN, "utf8"));
  writeFileSync(OUTPUT, buildIconData(readLucideIcons(), names));
  console.log(`wrote ${OUTPUT} (${names.length} icons)`);
}
